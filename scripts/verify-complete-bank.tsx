import assert from 'node:assert/strict';
import { readFile,writeFile } from 'node:fs/promises';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { createHash } from 'node:crypto';
import type {BaseQuestion} from '../src/types';
import {ALL_TOPIC_TYPES} from '../src/features/questions/topic-catalog';
import {EDUCATION_PROFILES,type SchoolGrade} from '../src/features/questions/quality-policy';
import {auditQuestion,questionVisualKey} from '../src/features/questions/quality';
import {visibleOptionKey} from '../src/features/questions/mechanical-quality';
import {QuestionRenderer} from '../src/features/questions/renderers/QuestionRenderer';
import {OptionRenderer} from '../src/features/questions/renderers/OptionRenderer';
import {publicVisualConfig} from '../src/features/questions/public-visual';
import {stemKey,type BankQuestion} from './generate-grade-bank';
import {checkArithmeticExplanations} from './question-proof-checks';
const [input,output]=process.argv.slice(2);
if(!input||!output)throw Error('Usage: private-bank.json report.json');
const bank=JSON.parse(await readFile(input,'utf8')) as {batchId:string;questions:BankQuestion[];summary:{perGrade:number;distribution:Record<string,unknown>}};
assert.equal(bank.questions.length,8000);
const ids=new Set<string>(),stems=new Set<string>(),visuals=new Set<string>();
const grades:Record<number,number>={},cells=new Map<string,number>();
let equalities=0,wrongKeysRejected=0,duplicateOptionsRejected=0;
for(const q of bank.questions){
  const report=auditQuestion(q);assert.ok(report.solverVerified,`${q.id}: proof`);assert.deepEqual([...report.errors,...report.reviewRequired],[],q.id);
  assert.equal(new Set(q.options.map(o=>visibleOptionKey(o.visualData))).size,4,q.id);
  assert.ok(!ids.has(q.id)&&!stems.has(stemKey(q))&&!visuals.has(questionVisualKey(q)),`Duplicate: ${q.id}`);
  ids.add(q.id);stems.add(stemKey(q));visuals.add(questionVisualKey(q));grades[q.targetGrade!]=(grades[q.targetGrade!]||0)+1;
  const cell=`${q.targetGrade}:${q.type}:${q.difficulty}`;cells.set(cell,(cells.get(cell)||0)+1);
  const arithmetic=checkArithmeticExplanations(q);assert.deepEqual(arithmetic.errors,[],q.id);equalities+=arithmetic.checked.length;
  const wrong:BaseQuestion={...q,correctOptionId:q.options.find(o=>o.id!==q.correctOptionId)!.id};assert.equal(auditQuestion(wrong).solverVerified,false);wrongKeysRejected++;
  const duplicate={...q,options:q.options.map((o,i)=>i===1?{...o,visualData:q.options[0].visualData}:o)};assert.ok(auditQuestion(duplicate).errors.length>0);duplicateOptionsRejected++;
  const shown={...q,visualConfig:publicVisualConfig(q)};
  const html=renderToStaticMarkup(<QuestionRenderer question={shown}/>);
  assert.doesNotMatch(html,/Müfredat çizimi eksik|görünümü tanımlı değil|Tanımsız sembol|\[object Object\]|NaN|correctOptionId|distractorNotes/,q.id);
  const rendered=q.options.map(o=>renderToStaticMarkup(<OptionRenderer option={{...o,id:'choice',label:'choice'}} questionType={q.type}/>));
  assert.equal(new Set(rendered).size,4,`${q.id}: same rendered options`);
}
assert.deepEqual(grades,{1:2000,2:2000,3:2000,4:2000});
for(const grade of [1,2,3,4] as SchoolGrade[])for(const type of ALL_TOPIC_TYPES)for(let d=1;d<=EDUCATION_PROFILES[grade].maxDifficulty;d++)assert.ok(cells.get(`${grade}:${type}:${d}`),`Missing coverage ${grade}/${type}/${d}`);
const result={batch:bank.batchId,total:ids.size,grades,topicsPerGrade:44,coveredTopicLevelCells:cells.size,uniqueStems:stems.size,uniqueVisuals:visuals.size,answerAndRenderChecks:'passed',arithmeticEqualities:equalities,wrongKeysRejected,duplicateOptionsRejected,individualHumanReview:false,sourceFileSha256:createHash('sha256').update(await readFile(input)).digest('hex'),distribution:bank.summary.distribution};
await writeFile(output,JSON.stringify(result,null,2));console.log(JSON.stringify({...result,distribution:undefined}));
